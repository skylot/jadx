package jadx.core.dex.visitors.fixaccessmodifiers;

import java.util.List;

import jadx.api.plugins.input.data.AccessFlags;
import jadx.api.plugins.input.data.IClassData;
import jadx.api.plugins.input.data.attributes.JadxAttrType;
import jadx.api.plugins.input.data.attributes.types.InnerClassesAttr;
import jadx.api.plugins.input.data.attributes.types.InnerClsInfo;
import jadx.core.dex.info.AccessInfo;
import jadx.core.dex.info.MethodInfo;
import jadx.core.dex.instructions.args.ArgType;
import jadx.core.dex.nodes.ClassNode;
import jadx.core.dex.nodes.MethodNode;
import jadx.core.dex.nodes.RootNode;
import jadx.core.dex.visitors.AbstractVisitor;
import jadx.core.dex.visitors.JadxVisitor;
import jadx.core.utils.exceptions.JadxException;

@JadxVisitor(
		name = "PrepareAccessFlags",
		desc = "Fix class access flags from attributes"
)
public class PrepareAccessFlags extends AbstractVisitor {
	private boolean fixAccessFlags;

	@Override
	public void init(RootNode root) throws JadxException {
		fixAccessFlags = !root.getArgs().isRespectBytecodeAccModifiers();
	}

	@Override
	public boolean visit(ClassNode cls) throws JadxException {
		if (fixAccessFlags) {
			process(cls);
		}
		return true;
	}

	/**
	 * Use access flags from 'inner classes' attribute
	 * Restore 'static' flag for member class if it was removed (for example, by R8).
	 * Constructors of non-static member class always have outer class instance as a first argument.
	 */
	private static void process(ClassNode cls) {
		IClassData clsData = cls.getClsData();
		if (clsData == null) {
			// synthetic class (generated by jadx)
			return;
		}
		InnerClassesAttr innerClassesAttr = cls.get(JadxAttrType.INNER_CLASSES);
		if (innerClassesAttr == null) {
			return;
		}
		InnerClsInfo innerClsInfo = innerClassesAttr.getMap().get(clsData.getType());
		if (innerClsInfo == null) {
			return;
		}
		AccessInfo innerAccessFlags = new AccessInfo(innerClsInfo.getAccessFlags(), AccessInfo.AFType.CLASS);
		if (!cls.getAccessFlags().equals(innerAccessFlags)) {
			cls.setAccessFlags(innerAccessFlags);
			cls.addDebugComment("Apply access flags from 'inner classes' attribute");
		}
		if (!cls.getAccessFlags().isStatic() && innerClsInfo.getOuterCls() != null) {
			ArgType outerType = ArgType.object(innerClsInfo.getOuterCls());
			if (verifyConstructors(cls, outerType)) {
				cls.setAccessFlags(cls.getAccessFlags().add(AccessFlags.STATIC));
				cls.addInfoComment("Make member class 'static'");
			}
		}
	}

	private static boolean verifyConstructors(ClassNode cls, ArgType outerType) {
		boolean found = false;
		for (MethodNode mth : cls.getMethods()) {
			MethodInfo mthInfo = mth.getMethodInfo();
			if (mthInfo.isConstructor()) {
				List<ArgType> argTypes = mthInfo.getArgumentsTypes();
				if (!argTypes.isEmpty() && argTypes.get(0).equals(outerType)) {
					return false;
				}
				found = true;
			}
		}
		return found;
	}
}
